#!/usr/bin/env node
/**
 * Writes lib/public-routes.js: every public docs route in a build, as a
 * locale-free key. lib/agent-read-log.js logs a request path only when its key
 * is in this list, so arbitrary client input (an email typed into a URL, a
 * token, a scanner probe) never reaches the function log.
 *
 * The list is committed so the deployed middleware never depends on build
 * order. A page added after the last sync is logged as "/(other)" until the
 * list is refreshed; nothing else breaks.
 *
 * Usage:
 *   yarn build && yarn sync:public-routes      # refresh the committed list
 *   node scripts/sync-public-routes.mjs --check [--strict]
 *     Compare the committed list with build/. Prints the drift. With --strict,
 *     exits 1 when they differ.
 */

import fs from 'fs';
import path from 'path';
import {fileURLToPath} from 'url';
import {DOC_SECTIONS} from '../lib/markdown-negotiation-paths.js';
import {routeKey} from '../lib/agent-read-log.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'lib', 'public-routes.js');
const SECTIONS = DOC_SECTIONS.split('|');

function walk(dir, prefix, keys) {
  for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
    const rel = `${prefix}/${entry.name}`;
    if (entry.isDirectory()) {
      walk(path.join(dir, entry.name), rel, keys);
    } else if (/\.(html|md)$/.test(entry.name)) {
      keys.add(routeKey(rel));
    }
  }
}

/** Collects route keys under the doc sections of a build directory. */
export function collectRoutes(buildDir) {
  const keys = new Set();
  for (const section of SECTIONS) {
    const dir = path.join(buildDir, section);
    if (fs.existsSync(dir)) {
      walk(dir, `/${section}`, keys);
    }
  }
  return [...keys].sort();
}

function render(routes) {
  return `// Generated by scripts/sync-public-routes.mjs from a docs build. Do not edit by hand.
// Refresh with: yarn build && yarn sync:public-routes
// Locale-free route keys (no trailing slash, index file or extension) for the doc sections.
export const PUBLIC_ROUTES = new Set(${JSON.stringify(routes, null, 2).replace(/"/g, "'")});
`;
}

async function main(argv) {
  const buildDir = path.join(ROOT, 'build');
  if (!fs.existsSync(buildDir)) {
    console.error('build/ not found. Run yarn build first.');
    process.exit(2);
  }
  const routes = collectRoutes(buildDir);
  if (routes.length === 0) {
    console.error('No doc routes found under build/. Run yarn build first.');
    process.exit(2);
  }
  if (!argv.includes('--check')) {
    fs.writeFileSync(OUT, render(routes));
    console.log(`✓ Wrote ${routes.length} public routes to lib/public-routes.js`);
    return;
  }
  const {PUBLIC_ROUTES} = await import('../lib/public-routes.js');
  const built = new Set(routes);
  const missing = routes.filter((route) => !PUBLIC_ROUTES.has(route));
  const removed = [...PUBLIC_ROUTES].filter((route) => !built.has(route));
  if (missing.length === 0 && removed.length === 0) {
    console.log(`✓ ${PUBLIC_ROUTES.size} public routes in sync with build/`);
    return;
  }
  const strict = argv.includes('--strict');
  const annotation = process.env.GITHUB_ACTIONS && !strict ? '::warning::' : '';
  const level = strict ? '✗' : '⚠';
  console.log(
    `${annotation}${level} lib/public-routes.js is out of date: ${missing.length} new route(s) will log as /(other), ${removed.length} removed route(s) still listed. Run yarn build && yarn sync:public-routes.`,
  );
  for (const route of missing.slice(0, 10)) console.log(`  + ${route}`);
  for (const route of removed.slice(0, 10)) console.log(`  - ${route}`);
  if (argv.includes('--strict')) process.exit(1);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main(process.argv.slice(2));
}
